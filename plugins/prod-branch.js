import { execFileSync } from 'node:child_process';
import { existsSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { experimental_readRawConfig as readWranglerConfig } from 'wrangler';

const WORKER_DIR = '_worker';

// Makes dist/ deployable by itself (`npx wrangler deploy`, no build step): the pre-bundled Worker plus a
// wrangler.jsonc derived from the repo's, pointing at it and serving dist/ itself as the assets.
export function writeWorkerFiles(outDir, projectRoot) {
	const wrangler = path.join(projectRoot, 'node_modules', 'wrangler', 'bin', 'wrangler.js');
	const workerDir = path.join(outDir, WORKER_DIR);
	rmSync(workerDir, { recursive: true, force: true });
	execFileSync(process.execPath, [wrangler, 'deploy', '--dry-run', '--outdir', workerDir], { cwd: projectRoot, stdio: 'pipe' });
	rmSync(path.join(workerDir, 'README.md'), { force: true });

	const { rawConfig } = readWranglerConfig({ config: path.join(projectRoot, 'wrangler.jsonc') });
	const { $schema, main, build, ...config } = rawConfig;
	const deployConfig = { ...config, main: `${WORKER_DIR}/index.js`, no_bundle: true, assets: { ...config.assets, directory: '.' } };
	writeFileSync(
		path.join(outDir, 'wrangler.jsonc'),
		`// Generated by plugins/prod-branch.js from the repo's wrangler.jsonc on every build. Edit that file, not this one.\n${JSON.stringify(deployConfig, null, '\t')}\n`,
	);
}

// dist/ is a git worktree of `prod`. After each build, `prod` is replaced with a single commit of dist/
// and FORCE-PUSHED to origin. Skipped when process.env.CI is set. Git failures only warn.
export default function prodBranch({ site, branch = 'prod', remote = 'origin' } = {}) {
	let outDir;
	let projectRoot;
	let active = false;
	const git = (args, cwd) => execFileSync('git', args, { cwd, encoding: 'utf8', stdio: 'pipe' }).trim();
	const tryGit = (args, cwd) => {
		try {
			return git(args, cwd);
		} catch {
			return null;
		}
	};
	const warn = (msg) => console.warn(`[prod-branch] ${msg}`);

	return {
		name: 'prod-branch',
		apply: 'build',

		configResolved(config) {
			outDir = path.resolve(config.root, config.build.outDir);
			projectRoot = path.dirname(config.configFile);
		},

		buildStart() {
			if (process.env.CI) return;
			try {
				if (!existsSync(path.join(outDir, '.git'))) {
					rmSync(outDir, { recursive: true, force: true });
					git(['worktree', 'prune']);
					tryGit(['fetch', '--quiet', remote, branch]);
					if (tryGit(['rev-parse', '--verify', '--quiet', `refs/heads/${branch}`])) {
						git(['worktree', 'add', '--quiet', outDir, branch]);
					} else if (tryGit(['rev-parse', '--verify', '--quiet', `refs/remotes/${remote}/${branch}`])) {
						git(['worktree', 'add', '--quiet', '-b', branch, outDir, `${remote}/${branch}`]);
					} else {
						git(['worktree', 'add', '--quiet', '--orphan', '-b', branch, outDir]);
					}
					console.log(`[prod-branch] dist/ is now a checkout of ${branch}`);
				}
				if (git(['branch', '--show-current'], outDir) !== branch) throw new Error(`dist/ is not on ${branch}`);
				active = true;
			} catch (err) {
				warn(`disabled for this build: ${err.message.split('\n')[0]}`);
			}
		},

		closeBundle() {
			if (!active) return;
			try {
				const cloudflare = site?.hosting === 'cloudflare';
				if (cloudflare) writeWorkerFiles(outDir, projectRoot);
				// dist/.git is a pointer file; keep it (and the deploy files) out of the Cloudflare upload
				writeFileSync(path.join(outDir, '.assetsignore'), cloudflare ? `.git\n.assetsignore\nwrangler.jsonc\n${WORKER_DIR}\n` : '.git\n');

				const source = `${git(['branch', '--show-current']) || 'detached'}@${git(['rev-parse', '--short', 'HEAD'])}`;
				const dirty = git(['status', '--porcelain']) ? ' (with uncommitted changes)' : '';

				git(['add', '--all', '--force', '.'], outDir);
				const tree = git(['write-tree'], outDir);
				const commit = git(['commit-tree', tree, '-m', `Build from ${source}${dirty}`], outDir);
				git(['reset', '--soft', commit], outDir);
				console.log(`[prod-branch] ${branch} → ${commit.slice(0, 7)} (build from ${source}${dirty})`);

				if (tryGit(['push', '--force', '--quiet', remote, `${branch}:${branch}`], outDir) === null) {
					warn(`could not push ${branch} to ${remote}; it is updated locally only.`);
				} else {
					console.log(`[prod-branch] pushed ${branch} to ${remote}`);
				}
			} catch (err) {
				warn(`skipped: ${err.message.split('\n')[0]}`);
			}
		},
	};
}
